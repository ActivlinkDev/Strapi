/**
 * Seed script: fills in every localized field of every localized single type,
 * so no page falls back to the hard-coded English in the React code and no
 * locale is left with an empty value.
 *
 * Coverage: all 14 localized single types (basket, checkout-success,
 * cookie-banner, customer-hub, device-input, display-device, display-offer,
 * error-page, lookup, my-contracts, portal-admin, shared-ui, start-page,
 * validate-customer) — 503 fields in 8 languages.
 *
 * It is additive and safe to re-run: for every locale it reads the current
 * entry, only writes keys that are currently empty, and leaves everything
 * already translated untouched. Pass --force to overwrite existing values.
 *
 * Regional locales (fr-BE, pt-BR, …) reuse their base language; locales with
 * no translation here fall back to English.
 *
 * Placeholders such as {count}, {destination}, {detail}, {phone}, {firstName},
 * {products}, {n} and {device} are substituted by the frontend and are kept
 * byte-identical across every language — do not translate or reorder them.
 *
 * Usage: node seed-missing-translations.js <adminEmail> <adminPassword> [--force] [--only=basket,lookup]
 */

const http = require('http');
const https = require('https');

const BASE_URL = process.env.STRAPI_URL || 'http://localhost:1337';
const args = process.argv.slice(2);
const FORCE = args.includes('--force');
const ONLY = (args.find((a) => a.startsWith('--only=')) || '').replace('--only=', '');
const positional = args.filter((a) => !a.startsWith('--'));
const EMAIL = positional[0];
const PASSWORD = positional[1];

if (!EMAIL || !PASSWORD) {
  console.error('Usage: node seed-missing-translations.js <adminEmail> <adminPassword> [--force] [--only=a,b]');
  process.exit(1);
}

function request(method, path, body, token) {
  return new Promise((resolve, reject) => {
    const url = new URL(BASE_URL + path);
    const isHttps = url.protocol === 'https:';
    const lib = isHttps ? https : http;
    const payload = body ? JSON.stringify(body) : null;

    const options = {
      hostname: url.hostname,
      port: url.port || (isHttps ? 443 : 80),
      path: url.pathname + url.search,
      method,
      headers: {
        'Content-Type': 'application/json',
        ...(token ? { Authorization: `Bearer ${token}` } : {}),
        ...(payload ? { 'Content-Length': Buffer.byteLength(payload) } : {}),
      },
    };

    const req = lib.request(options, (res) => {
      let data = '';
      res.on('data', (chunk) => (data += chunk));
      res.on('end', () => {
        try {
          resolve({ status: res.statusCode, body: JSON.parse(data) });
        } catch {
          resolve({ status: res.statusCode, body: data });
        }
      });
    });

    req.on('error', reject);
    if (payload) req.write(payload);
    req.end();
  });
}

